def finding_bars(items: list[tuple[str, float, str, bool]]) -> str:
    """Animated horizontal bars for st.html. items = [(label, fraction 0..1, value_text, orange?)]."""
    out = []
    for label, frac, text, orange in items:
        out.append(f'<div class="flabel"><span>{label}</span><b>{text}</b></div>'
                   f'<div class="fbar{" orange" if orange else ""}"><span style="--w:{max(0.0, min(frac, 1.0)) * 100:.1f}%"></span></div>')
    return "".join(out)
